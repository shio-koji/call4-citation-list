#!/usr/bin/env python3
"""論文（雑誌掲載）に絞った傾向分析を中間報告にする。"""
import json, os, re, collections

HERE = os.path.dirname(os.path.abspath(__file__))
w = json.load(open(os.path.join(HERE, "out_works.json")))
cases = {c["id"]: c for c in
         json.load(open(os.path.join(HERE, "cache", "cases_list.json")))["cases"]}
tag = lambda c: "・".join(t for t in cases[c].get("tags", []) if t != "アーカイブ")

art = [r for r in w if r["kind"] == "論文（雑誌掲載）"]
bk = [r for r in w if r["kind"] == "書籍"]

JOURNALS = ["ジュリスト", "法律時報", "法学教室", "法学セミナー", "法曹時報", "民商法雑誌",
            "法学協会雑誌", "国家学会雑誌", "法学論叢", "法学研究", "自治研究",
            "法律のひろば", "判例評論", "重要判例解説", "論究ジュリスト", "季刊労働法",
            "日本労働研究雑誌", "判例時報", "判例タイムズ", "法と政治", "法政論集",
            "紀要", "論集", "論叢", "年報", "法政研究", "早稲田法学", "法社会学",
            "比較法研究", "公法研究", "憲法問題", "国際人権", "現代思想", "都市計画",
            "ランドスケープ研究", "造園雑誌", "建築雑誌", "学会誌", "世界", "法学新報",
            "民事研修"]
ERA = (("平成", 1988), ("昭和", 1925), ("令和", 2018), ("大正", 1911), ("明治", 1867))


def blob(r):
    return f"{r['source'] or ''} {r['title'] or ''} {r.get('context') or ''}"


def journal(r):
    hit = [j for j in JOURNALS if j in blob(r)]
    return max(hit, key=len) if hit else None


def year(r):
    s = blob(r)
    for x in re.findall(r"(1[89]\d\d|20[0-2]\d)", s):
        if 1880 <= int(x) <= 2026:
            return int(x)
    for e, base in ERA:
        m = re.search(e + r"\s?(\d{1,2})年", s)
        if m:
            return base + int(m.group(1))
    return None


jc = collections.Counter(j for j in (journal(r) for r in art) if j)
n_j = sum(jc.values())
ya = sorted(y for y in (year(r) for r in art) if y)
yb = sorted(y for y in (year(r) for r in bk) if y)
ca = collections.Counter(); cb = collections.Counter()
for r in w:
    for c in r["出現ケース"]:
        if r["kind"] == "論文（雑誌掲載）":
            ca[c] += 1
        elif r["kind"] == "書籍":
            cb[c] += 1
ratio = sorted([(c, ca[c], cb[c], ca[c] / (ca[c] + cb[c]))
                for c in set(ca) | set(cb) if ca[c] + cb[c] >= 25], key=lambda x: -x[3])
cross_a = sorted([r for r in art if r["ケース数"] > 1],
                 key=lambda r: (-r["ケース数"], -r["出現回数"]))
m1a = sum(1 for r in art if r["ケース数"] == 1)
m1b = sum(1 for r in bk if r["ケース数"] == 1)

L = []; a = L.append
a("# 中間報告⑥ 論文だけを見ると何が違うか\n")
a("書籍を除き、**雑誌に載った論文だけ**に絞って傾向を調べました。"
  "結論を先に言うと、**論文と書籍はまったく違う使われ方をしています。**\n")
a("---\n")
a("## いちばん大きな違い: 論文はケースを越えない\n")
a("| | 1ケースだけで引用 | 複数ケースで引用 |")
a("|---|---:|---:|")
a(f"| 論文（{len(art)}件） | {m1a}件（**{m1a/len(art):.1%}**） | {len(art)-m1a}件（{(len(art)-m1a)/len(art):.1%}） |")
a(f"| 書籍（{len(bk)}件） | {m1b}件（{m1b/len(bk):.1%}） | {len(bk)-m1b}件（**{(len(bk)-m1b)/len(bk):.1%}**） |")
a("")
a(f"**論文の{m1a/len(art):.0%}は1つの訴訟でしか引かれません。** 書籍が複数ケースで引かれる割合"
  f"（{(len(bk)-m1b)/len(bk):.1%}）は、論文（{(len(art)-m1a)/len(art):.1%}）の"
  f"**約{((len(bk)-m1b)/len(bk))/((len(art)-m1a)/len(art)):.0f}倍**です。\n")
a("使い分けがはっきりしています。\n")
a("- **書籍（体系書・注釈書）** — 「憲法14条の平等とは何か」のような**共通の土台**を示すために引く。"
  "だから分野が違っても同じ本に行き着く")
a("- **論文** — 「同性婚と憲法24条」「教員の給特法と労基法」のような"
  "**その訴訟に固有の論点**を論じたものを引く。だから他の訴訟では使われない\n")
a("**訴訟における論文の価値は、汎用性ではなく的確さにある**ということです。"
  "争点にぴったり合う先行研究が1本あるかどうかが効く。\n")
a("---\n")
a("## 掲載誌: 上位4誌で3分の1\n")
a(f"掲載誌が特定できたのは {n_j}件（{n_j/len(art):.0%}）。残りは誌名が書式から読み取れなかったものです。\n")
a("| 掲載誌 | 件数 |")
a("|---|---:|")
for j, n in jc.most_common(15):
    a(f"| {j} | {n} |")
a("")
top4 = sum(n for _, n in jc.most_common(4))
a(f"**上位4誌（法律時報・ジュリスト・論集・法学セミナー）で{top4}件**、特定できた分の{top4/n_j:.0%}を占めます。\n")
a("注目すべきは **『法学セミナー』が31件で4位**に入っていることです。"
  "法学セミナーは学生・実務家向けの入門寄りの雑誌で、専門誌ではありません。"
  "**裁判所に読ませる書面では、難解な専門論文より『分かりやすく整理された解説』が"
  "武器になる**、という実務の判断が見えます。\n")
a("`論集` `論叢` `紀要` `年報` を合計すると"
  f"{sum(jc.get(k,0) for k in ['論集','論叢','紀要','年報'])}件で、"
  "これは大学の紀要類です。商業誌だけでなく、大学が出す研究誌も実際に訴訟で使われています。\n")
a("---\n")
a("## 年代: 論文のほうが新しい\n")
a("| | 中央値 | 四分位範囲 |")
a("|---|---:|---|")
a(f"| 論文 | **{ya[len(ya)//2]}年** | {ya[len(ya)//4]}〜{ya[len(ya)*3//4]}年 |")
a(f"| 書籍 | {yb[len(yb)//2]}年 | {yb[len(yb)//4]}〜{yb[len(yb)*3//4]}年 |")
a("")
da = collections.Counter(y // 10 * 10 for y in ya)
db = collections.Counter(y // 10 * 10 for y in yb)
a("| 年代 | 論文 | 書籍 |")
a("|---|---:|---:|")
for d in sorted(set(da) | set(db)):
    if da.get(d, 0) + db.get(d, 0) >= 10:
        a(f"| {d}年代 | {da.get(d,0)} | {db.get(d,0)} |")
a("")
a("差は中央値で2年と小さいのですが、**古い側の裾が違います。**"
  "書籍は1880年代（明治期の民法注釈）から引かれるのに対し、論文は1920年代より前がほぼありません。"
  "**古い法解釈をたどるときは書籍、最近の議論を引くときは論文**、という役割分担です。\n")
a("2010年代が論文・書籍とも最多で、直近15年の研究が訴訟の主戦力になっています。\n")
a("---\n")
a("## ケースによって論文と書籍の比率が大きく違う\n")
a("文献を25件以上引いている22ケースで、論文の割合を出しました。\n")
a("### 論文の比率が高いケース\n")
a("| 論文の割合 | 論文 | 書籍 | ケース | 主題 |")
a("|---:|---:|---:|---|---|")
for c, x, y, r in ratio[:8]:
    a(f"| **{r:.0%}** | {x} | {y} | [{cases[c]['title'][:28]}]"
      f"(https://www.call4.jp/info.php?type=items&id={c}) | {tag(c)[:20]} |")
a("")
a("### 書籍の比率が高いケース\n")
a("| 論文の割合 | 論文 | 書籍 | ケース | 主題 |")
a("|---:|---:|---:|---|---|")
for c, x, y, r in ratio[-8:]:
    a(f"| {r:.0%} | {x} | {y} | [{cases[c]['title'][:28]}]"
      f"(https://www.call4.jp/info.php?type=items&id={c}) | {tag(c)[:20]} |")
a("")
a("**この差には意味がありそうです。**\n")
a("論文の比率が高い上位は、`地方議会の少数派議員潰し`（62%）、`夫婦別姓`（61%）、"
  "`黙秘権`（57%）、`教員の働き方`（57%）、`コロナ特措法`（52%）。"
  "**どれも体系書に答えが書いていない、比較的新しい・争いのある論点**です。"
  "教科書が無いから、個別の論文を積み上げるしかない。\n")
a("逆に書籍の比率が高いのは `同性婚仙台`（論文12%）、`ジャーナリストの渡航の自由`（14%）、"
  "`在外選挙権`（17%）、`マリアージュしたいねん`（18%）。"
  "**憲法の確立した枠組み（婚姻の自由、移動の自由、選挙権）に乗せて争う訴訟**で、"
  "体系書で足りるということです。\n")
a("面白いのは**同性婚訴訟が両側に現れる**ことです。"
  "`結婚の自由をすべての人に`は論文197件・書籍298件と桁違いの物量、"
  "`マリアージュしたいねん`は書籍中心（論文18%）、`同性婚仙台`はさらに書籍寄り（12%）。"
  "同じ争点でも、弁護団によって論証の組み立て方が違うことが数字に出ています。\n")
a("---\n")
a(f"## 複数ケースで引用された論文は{len(cross_a)}件しかない\n")
a("書籍145件に対し、論文はこれだけです。全部挙げます。\n")
a("| ケース数 | 回数 | 論文 |")
a("|---:|---:|---|")
for r in cross_a:
    au = f"{r['author']} " if r["author"] else ""
    a(f"| {r['ケース数']} | {r['出現回数']} | {au}「{r['title'][:42]}」 {r['source'][:22]} |")
a("")
a("**ほぼ全部が同性婚・家族法まわり**です。"
  "星野茂「わが国における同性愛者をめぐる家族法上の諸問題」（法律論叢、1997年）が3ケース、"
  "大村敦志「性転換・同性愛と民法(下)」（ジュリスト1081号）が3ケース。"
  "1990年代に書かれたこれらの論文が、20年以上経って複数の訴訟の土台になっています。\n")
a("**論文が複数の訴訟をつなぐのは、同じ社会課題が複数の裁判で争われているときだけ**"
  "ということです。書籍のように分野を越えることはありません。\n")
a("---\n")
a("## この分析の限界\n")
a(f"- **掲載誌が特定できたのは{n_j/len(art):.0%}だけ**です。"
  "誌名リストに載っていない雑誌や、書式が崩れているものは数えられていません")
a("- **年は出典欄の数字から拾っています。** 巻号数を年と誤認している可能性があります")
a("- **省略引用（`前掲注(24)`）は拾えていません。** 実際の引用回数はもっと多いはずです")
a("- **人手の正誤確認はしていません。** 傾向としては読めますが、個々の数字は概算です\n")
a("---\n")
a("## データの置き場所\n")
a("| ファイル | 中身 |")
a("|---|---|")
a("| **公開サイト** | https://shio-koji.github.io/call4-citation-list/ （種類で「論文」に絞れます） |")
a(f"| `out_works.json` | 名寄せ後の全著作（論文{len(art)}件を含む） |")
a("| `16_report_articles.py` | この分析のスクリプト |")

open(os.path.join(HERE, "中間報告06_論文に絞った傾向.md"), "w").write("\n".join(L))
print("\n".join(L[:30]))
