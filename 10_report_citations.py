#!/usr/bin/env python3
"""全件の抽出結果を、人が読める中間報告にする。"""
import json, os, collections, re

HERE = os.path.dirname(os.path.abspath(__file__))
m = json.load(open(os.path.join(HERE, "out_citations.json")))
survey = {r["id"]: r for r in json.load(open(os.path.join(HERE, "out_survey.json")))}
cases_all = {c["id"]: c for c in
             json.load(open(os.path.join(HERE, "cache", "cases_list.json")))["cases"]}
CV = "執筆者の業績（引用ではない）"

real = [r for r in m if r["kind"] != CV]
cv = [r for r in m if r["kind"] == CV]
bykind = collections.Counter(r["kind"] for r in real)
bycase = collections.Counter()
for r in real:
    for c in r["出現ケース"]:
        bycase[c] += 1
n_doc = sum(s["n"] for s in survey.values())
n_txt = len([f for f in os.listdir(os.path.join(HERE, "cache", "text"))
             if json.load(open(os.path.join(HERE, "cache", "text", f))).get("text")])
cross = sorted([r for r in real if len(r["出現ケース"]) > 1],
               key=lambda r: (-len(r["出現ケース"]), -r["出現回数"]))
zero = [c for c in cases_all if bycase.get(c, 0) == 0]

fmt = lambda r: (f"{r['author']} " if r["author"] else "") + \
    (f"「{r['title']}」" if r.get("bracket") == "「" else
     f"『{r['title']}』" if r.get("bracket") else r["title"]) + \
    (f" {r['source']}" if r["source"] else "")

L = []; a = L.append
a("# 中間報告④ 全96ケースの引用文献リストができた\n")
a("試作を全件に広げました。**公開されている公共訴訟96件すべて**が対象です。\n")
a("**公開サイト: https://shio-koji.github.io/call4-citation-list/**\n")
a("---\n")
a("## 結論\n")
a(f"訴訟資料 **{n_doc:,}件**から、**{len(real):,}件の学術文献**を抽出しました。\n")
a("| | |")
a("|---|---:|")
for k, n in bykind.most_common():
    a(f"| {k} | {n:,}件 |")
a(f"| **合計** | **{len(real):,}件** |")
a("")
a(f"ほかに、意見書の執筆者自身の著作リストが {len(cv):,}件（別枠）。\n")
a("---\n")
a("## データの取り方\n")
a("### 1. 訴訟資料の本文を全件取得した\n")
a(f"96ケースすべてに `list_documents` を掛け、出てきた **{n_doc:,}件** の資料に "
  "`fetch_document_text` を掛けました（`12_fetch_all_texts.py`）。\n")
a(f"**本文が取れたのは {n_txt:,}件（{n_txt/n_doc:.1%}）。**\n")
a("取得には **2.26時間** かかりました。1件あたり中央値5.2秒です。"
  "CALL4側がリクエストごとに本文抽出（画像スキャンのOCRを含む）を実行しているためで、"
  "単なるファイル配信ではありません。\n")
a("**同時接続は3本に抑えました。** 逐次だと8.3時間かかりますが、"
  "相手は小規模な団体のサーバーで1件ごとに重い処理をしています。"
  "5〜6本にすれば3.5時間程度まで縮みますが、負荷をかけすぎる判断です。\n")
a("`has_text` フラグは見ずに全件叩いています。中間報告②で"
  "「フラグが `False` でも2割は本文が取れる」と分かっていたためです。\n")
a("### 2. 本文から引用を抜いた\n")
a("`09_extract_citations.py`。仕組みは試作のときと同じで、"
  "**日本語の文献引用は書誌情報がタイトルの直後に来る**という性質だけを使います。\n")
a("```")
a("芦部信喜『憲法〔第8版〕』(岩波書店、2023年)122頁")
a("  └著者   └────タイトル────┘ └──出版社・年──┘└頁┘")
a("```\n")
a("鉤括弧を見つけたら**直後20〜25文字だけ**を見て、出版社名・括弧に入った発行年・"
  "すぐ続く頁数のいずれかがあるものを引用と判定します。"
  "訴訟書面の自己参照（`準備書面12頁`）、判例（`民集59巻7号2087頁`）、"
  "証拠番号（`甲15・3頁`）、本文中の強調（`「特定活動」`）は除外しました。\n")
a(f"抽出そのものは **8秒**で終わります。時間がかかるのは取得だけです。\n")
a("### 3. PDFへのリンクを張った\n")
a("資料PDFのURLはAPIに含まれないので、資料一覧ページのHTMLから拾いました（`13_fetch_matpages.py`）。"
  "**7,090件中7,079件（99.8%）**で対応づいています。\n")
a("---\n")
a("## いちばん面白かった結果: 分野を越えて引用される定番文献がある\n")
a(f"**{len(cross)}件**の文献が、複数の訴訟で引用されていました。上位はこれです。\n")
a("| ケース数 | 引用回数 | 文献 |")
a("|---:|---:|---|")
for r in cross[:15]:
    a(f"| {len(r['出現ケース'])} | {r['出現回数']} | {fmt(r)[:66]} |")
a("")
a("**これは1ケースずつ見ていては絶対に見えない情報**です。"
  "全件を横断して初めて「公共訴訟という営みが、どの学術的蓄積の上に立っているか」が見えます。\n")
a("長谷部恭男編『注釈日本国憲法』が7ケース、我妻榮『親族法』が4ケースで65回。"
  "憲法学と家族法学の定番書が、分野の違う訴訟をまたいで参照されています。\n")
a("---\n")
a("## ケース別\n")
top = sorted(bycase.items(), key=lambda x: -x[1])[:15]
a("**引用が多い上位15ケース**\n")
a("| 引用 | 資料 | ケース |")
a("|---:|---:|---|")
for c, n in top:
    a(f"| {n} | {survey[c]['n']} | [{cases_all[c]['title'][:40]}]"
      f"(https://www.call4.jp/info.php?type=items&id={c}) |")
a("")
a(f"**引用が0件のケースが {len(zero)}件**あります。")
a("資料が未公開のケース、証拠中心で学説を引かないケース、"
  "そもそも書面が少ないケースなどです。"
  "ケースによって引用の濃さが大きく違うこと自体が結果として意味を持ちます。"
  "**どの訴訟が学術的な議論に支えられているかが件数として見える**ということなので。\n")
a("---\n")
a("## 精度について正直に書いておくこと\n")
a("**自動抽出の結果で、人手による確認を経ていません。** 取りこぼすより余分に拾う側に倒してあります。\n")
a("目視で確認した範囲では:\n")
a("- **正しく取れているもの** — 大半。著者・書名・出版社・年が揃った形で取れる")
a("- **まだ混じる雑音** — 入れ子の鉤括弧で境界を誤るもの（`『「憲法上の権利』` など）、"
  "参考文献リストで次の文献が出典欄に流れ込むもの")
a("- **取りこぼし** — `前掲注(24)31頁` のような**2回目以降の省略引用**は、"
  "初出の書誌情報と結びつけていないため拾えていない\n")
a(f"**精度は数値化していません。** {len(m):,}件を1件ずつ人が判定していないため、"
  "「精度◯%」と書けるだけの根拠がないからです。"
  "必要ならサンプルを取って人が正誤を付ける作業が要ります。\n")
a("---\n")
a("## 次にやるとよいこと\n")
a("1. **省略引用の解決** — `前掲注(24)` を初出の文献に結びつける。同一文書内の注番号を辿ればできる")
a("2. **判例の抽出** — `最大判平17.9.14民集59-7-2087` の形は定型なので機械的に取れる。"
  "「どの訴訟がどの判例を引いたか」の関係図が副産物で作れる")
a("3. **証拠として提出された文献** — 甲号証には学術論文そのものが提出されていることがある。"
  "学者にとってはこちらも価値が高い")
a("4. **書誌の名寄せ** — 版違い（`憲法(第7版)` と `憲法〔第8版〕`）を同じ著作としてまとめる\n")
a("---\n")
a("## データの置き場所\n")
a("| ファイル | 中身 |")
a("|---|---|")
a(f"| **公開サイト** | https://shio-koji.github.io/call4-citation-list/ |")
a(f"| `out_引用文献_候補.csv` | 抽出した全{len(m):,}件（Excelで開けます） |")
a("| `out_citations.json` | 同上（生データ） |")
a("| `docs/data.json` | 公開サイトが読んでいるデータ |")
a("| `cache/text/<資料ID>.json` | 取得した本文 7,090件 |")
a("| `cache/pdf_urls.json` | 資料IDとPDFのURLの対応表 |")

open(os.path.join(HERE, "中間報告04_全96ケースの引用文献リスト.md"), "w").write("\n".join(L))
print("\n".join(L[:30]))
