#!/usr/bin/env python3
"""引用抽出の試作結果を、人が読める中間報告にする。"""
import json, os, collections, re

HERE = os.path.dirname(os.path.abspath(__file__))
m = json.load(open(os.path.join(HERE, "out_citations.json")))
survey = {r["id"]: r for r in json.load(open(os.path.join(HERE, "out_survey.json")))}
TARGETS = ["I0000090", "I0000111", "I0000120", "I0000159"]
CV = "執筆者の業績（引用ではない）"

real = [r for r in m if r["kind"] != CV]
cv = [r for r in m if r["kind"] == CV]
bykind = collections.Counter(r["kind"] for r in real)
bycase = collections.Counter()
for r in real:
    for c in r["出現ケース"]:
        bycase[c] += 1
n_doc = sum(survey[c]["n"] for c in TARGETS)

fmt = lambda r: (f"{r['author']} " if r["author"] else "") + \
    (f"「{r['title']}」" if r.get("bracket") == "「" else
     f"『{r['title']}』" if r.get("bracket") else r["title"]) + \
    (f" {r['source']}" if r["source"] else "")

L = []; a = L.append
a("# 中間報告③ 引用されている文献リストを試しに作ってみた\n")
a("当初やりたかった「訴訟で引用している論文リスト」を、**4ケースに絞って実際に作った**結果です。\n")
a("---\n")
a("## 結論\n")
a(f"**作れます。** 4ケース・資料{n_doc}件から、**{len(real)}件の学術文献**を機械的に取り出せました。\n")
a("| | |")
a("|---|---:|")
for k, n in bykind.most_common():
    a(f"| {k} | {n}件 |")
a(f"| **合計** | **{len(real)}件** |")
a("")
a("中身は例えばこういうものです。**著者・書名・出版社・発行年・頁まで揃った状態**で取れます。\n")
picks = [r for r in real if r["author"] and r["source"] and len(r["source"]) > 8][:8]
for r in picks:
    a(f"- {fmt(r)}")
a("")
a("---\n")
a("## どうやって作ったか\n")
a("### 1. 対象を4ケースに絞った\n")
a("全96ケースでは試作にならないので、**意見書（専門家が書く文書。学術引用が集中する）が多く、"
  "かつ資料数が扱える範囲**のケースを選びました。テーマが偏らないよう分野も散らしています。\n")
a("| ケースID | ケース名 | 資料数 | 分野 |")
a("|---|---|---:|---|")
names = {"I0000090": ("司法の独立を脅かす岡口裁判官の罷免訴追に反対します！", "司法"),
         "I0000111": ("日米同性カップル在留資格訴訟", "ジェンダー・入管"),
         "I0000120": ("神宮外苑を守ろう訴訟", "環境"),
         "I0000159": ("日本でもマリアージュしたいねん（同性婚）", "ジェンダー")}
for c in TARGETS:
    a(f"| `{c}` | {names[c][0]} | {survey[c]['n']} | {names[c][1]} |")
a("")
a("### 2. 資料の本文を全部取った\n")
a(f"`list_documents` で資料一覧を取り、`fetch_document_text` で本文を落としました（`08_fetch_case_texts.py`）。\n")
a(f"**{n_doc}件すべてで本文が取れました（100%）。** `has_text` フラグに関係なく全部叩いています。"
  "中間報告②で「フラグが `False` でも2割は取れる」と分かっていたためで、実際このやり方で取りこぼしゼロになりました。\n")
a("### 3. 本文から引用箇所を抜いた\n")
a("`09_extract_citations.py`。仕組みは単純で、**日本語の文献引用は書誌情報がタイトルの直後に来る**"
  "という性質だけを使っています。\n")
a("```")
a("芦部信喜『憲法〔第8版〕』(岩波書店、2023年)122頁")
a("  └著者   └────タイトル────┘ └──出版社・年──┘└頁┘")
a("```\n")
a("鉤括弧（`『』` `「」`）を見つけたら、**その直後20〜25文字だけ**を見て、"
  "出版社名・括弧に入った発行年・すぐ続く頁数のいずれかがあるものを引用と判定します。\n")
a("### 4. 紛らわしいものを外した\n")
a("訴訟書面には、引用とまったく同じ形をした**別物**が大量にあります。これらを明示的に除外しました。\n")
a("| 外したもの | 例 | なぜ |")
a("|---|---|---|")
a("| 書面の自己参照 | `準備書面12頁` `原判決43頁` | 文献ではなく訴訟書類 |")
a("| 判例の引用 | `民集59巻7号2087頁` | 文献ではなく裁判例。抽出ロジックが別物なので今回は対象外 |")
a("| 証拠番号 | `甲15・3頁` | 提出物への参照 |")
a("| 本文中の強調 | `「特定活動」` `『法の支配』` | 用語を括弧で囲っただけ |")
a("")
a("**最後の「本文中の強調」が一番やっかい**でした。最初の版では在留資格の"
  "`「特定活動」` を26回、`「定住者」` を17回も文献として拾ってしまっていました。"
  "「直後にしか書誌情報を見ない」という制約を入れて解決しています。"
  "用語の強調は、後ろに出版社も発行年も続かないためです。\n")
a("---\n")
a("## 予想していなかった発見: 意見書の末尾には執筆者の業績リストが付く\n")
a(f"抽出結果に、明らかに引用ではない文献が大量に混じりました。**{len(cv)}件**あります。\n")
a("意見書（専門家の鑑定書）の末尾には、執筆者自身の**経歴と主要業績**が載っているためです。\n")
if cv:
    a("```")
    for r in cv[:4]:
        a(f"{fmt(r)[:78]}")
    a("```\n")
a("これは**「訴訟で引用された文献」ではなく「意見書を書いた学者の著作」**なので、"
  "同じ扱いにはできません。ただし捨てるべきものでもなく、"
  "**「どの分野の誰が意見書を書いたか」を示す別の価値**があります。"
  "そこで消さずに、`執筆者の業績（引用ではない）` という種類を立てて分けました。\n")
a("判定は「主要業績」「略歴」などの見出しからの位置で行っています。"
  "見出し以降しばらくの範囲に現れた文献は業績リストとみなす、という単純な方法です。\n")
a("---\n")
a("## ケースごとの結果\n")
a("| ケース | 引用文献 |")
a("|---|---:|")
for c in TARGETS:
    a(f"| {names[c][0][:30]} | {bycase.get(c, 0)}件 |")
a("")
a(f"**ケースによって10倍以上の差**があります。`I0000120`（神宮外苑）は資料{survey['I0000120']['n']}件に対し"
  f"{bycase.get('I0000120', 0)}件しかありません。環境訴訟は行政手続や事実関係が争点の中心で、"
  "学説を引く場面が少ないためと考えられます。"
  "逆に憲法解釈が正面から争われるケース（同性婚・裁判官弾劾）では学術引用が濃く出ます。\n")
a("**この差自体が結果として意味を持ちます。**「どの訴訟が学術的な議論に支えられているか」が"
  "件数として見えるということなので。\n")
a("---\n")
a("## 精度について正直に書いておくこと\n")
a("**この結果は候補であって、確定ではありません。** 人が見て捨てる前提で、"
  "取りこぼすより余分に拾う側に倒してあります。\n")
a("目視で確認した範囲では:\n")
a("- **正しく取れているもの** — 大半。`芦部信喜『憲法〔第8版〕』(岩波書店、2023年)` のように"
  "著者・書名・出版社・年が揃った形で取れる")
a("- **まだ混じる雑音** — 引用の形をした本文中の強調が数件。"
  "`「司法の本質は『少数者保護』であるから…」` のような入れ子の鉤括弧で境界を誤る")
a("- **取りこぼし** — `前掲注(24)31頁` のような**2回目以降の省略引用**は、"
  "初出の書誌情報と結びつけていないため単独では拾えていない\n")
a("**数値化はしていません。** 273件を1件ずつ人が判定していないため、"
  "「精度◯%」と書けるだけの根拠がまだ無いからです。"
  "本番までにやるなら、サンプルを取って人が正誤を付ける作業が要ります。\n")
a("---\n")
a("## 次にやるとよいこと\n")
a("1. **省略引用の解決** — `前掲注(24)` を初出の文献に結びつける。同一文書内の注番号を辿ればできる")
a("2. **判例の抽出** — 今回は外したが、`最大判平17.9.14民集59-7-2087` の形は定型なので機械的に取れる。"
  "「どの訴訟がどの判例を引いたか」の関係図が副産物で作れる")
a("3. **証拠として提出された文献** — 甲号証には学術論文そのものが提出されていることがある。"
  "`証拠` カテゴリ1,956件を見れば「訴訟で証拠になった論文」が拾える。学者にとってはこちらも価値が高い")
a("4. **全96ケースへの展開** — 本文取得は約2時間、抽出は数分。規模の問題は無い\n")
a("---\n")
a("## データの置き場所\n")
a("| ファイル | 中身 |")
a("|---|---|")
a("| `out_引用文献_候補.csv` | **抽出した273件の全件**（Excelで開けます。引用箇所の前後の文章つき） |")
a("| `out_citations.json` | 同上（生データ） |")
a("| `08_fetch_case_texts.py` | 対象4ケースの本文を取るスクリプト |")
a("| `09_extract_citations.py` | 引用を抽出するスクリプト |")
a("| `cache/text/<資料ID>.json` | 取得した本文そのもの |")

open(os.path.join(HERE, "中間報告03_引用文献リストの試作.md"), "w").write("\n".join(L))
print("\n".join(L[:34]))
